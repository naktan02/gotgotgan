import { createHash } from 'node:crypto'
import { writeFile } from 'node:fs/promises'

// Public-domain reference data, never member imports or live query results.
const revision = 'f1890d9f152c896d250a77557a5751a93d494776'
const root = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${revision}/geojson/`
const sources = [
  ['country', 'ne_110m_admin_0_countries.geojson', '6866c877d39cba9c357620878839b336d569f8c662d3cfab4cb1dbe2d39c977f'],
  ['city', 'ne_110m_populated_places.geojson', 'a86028b083182b68c7620fc6e1a8a47ee547cb9cd2fb62ccbb78bea786440899'],
]

function points(coordinates) {
  return typeof coordinates[0] === 'number' ? [coordinates] : coordinates.flatMap(points)
}

function extent(coordinates) {
  const values = points(coordinates)
  const longitudes = [...new Set(values.map(([longitude]) => longitude))].sort((a, b) => a - b)
  let widest = -1
  let west = longitudes[0]
  let east = longitudes.at(-1)
  for (let index = 0; index < longitudes.length; index += 1) {
    const current = longitudes[index]
    const next = longitudes[(index + 1) % longitudes.length]
    const gap = next + (index === longitudes.length - 1 ? 360 : 0) - current
    if (gap > widest) { widest = gap; west = next; east = current }
  }
  const latitudes = values.map(([, latitude]) => latitude)
  return { west, south: Math.max(-85.051129, Math.min(...latitudes)), east, north: Math.min(85.051129, Math.max(...latitudes)) }
}

const rows = []
for (const [kind, file, digest] of sources) {
  const response = await fetch(root + file, { signal: AbortSignal.timeout(30_000) })
  if (!response.ok) throw new Error(`Geographic source unavailable: ${response.status}`)
  const raw = await response.text()
  if (createHash('sha256').update(raw).digest('hex') !== digest) throw new Error('Geographic source checksum changed')
  for (const { properties: value, geometry } of JSON.parse(raw).features) {
    const name = value.NAME_KO || value.NAME_EN || value.NAME
    const names = [...new Set([name, value.NAME, value.NAME_EN, value.NAME_LONG, value.FORMAL_EN, value.NAMEASCII]
      .filter((item) => typeof item === 'string' && item.trim()))]
    const location = kind === 'country'
      ? { longitude: value.LABEL_X, latitude: value.LABEL_Y }
      : { longitude: geometry.coordinates[0], latitude: geometry.coordinates[1] }
    rows.push({ key: `natural-earth:${kind}:${value.NE_ID}`, kind, name, names,
      countryCode: value.ISO_A2_EH ?? value.ISO_A2,
      location, bounds: kind === 'country' ? extent(geometry.coordinates) : null })
  }
}
rows.sort((a, b) => a.key.localeCompare(b.key))
const destination = new URL('../backend/src/modules/areas/adapters/geographic-catalog/reference-data.generated.ts', import.meta.url)
await writeFile(destination, `// Generated by scripts/generate-geographic-catalog.mjs; Natural Earth v5.1.2, public domain.\n// Source revision: ${revision}. Do not edit by hand.\nimport type { GeographicDestination } from '../../domain/geographic-destination.js'\n\nexport const geographicReferenceData: readonly GeographicDestination[] = [\n${rows.map((row) => `  ${JSON.stringify(row)},`).join('\n')}\n]\n`)
console.log(`Generated ${rows.length} public geographic destinations`)
